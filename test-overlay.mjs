import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const template=fs.readFileSync(new URL('./overlay.js',import.meta.url),'utf8');
const context=vm.createContext({});
vm.runInContext(template.replace('__CATALOG__',JSON.stringify({'newChat':'新建对话','settings':'设置'}))+';globalThis.overlay=__claudeGatewayZhOverlay;',context);
let variant='dynamic-a';
const original=new Proxy(Object.freeze({newChat:'New chat', untouched:'English', 'secret:key':'unchanged'}),{get(target,key){if(key==='variant')return variant;return Reflect.get(target,key);}});
const patched=context.overlay(original);
assert.equal(patched.newChat,'新建对话');
assert.equal(patched.settings,'设置');
assert.equal(patched.untouched,'English');
assert.equal(patched['secret:key'],'unchanged');
assert.equal(patched.variant,'dynamic-a');
variant='dynamic-b';assert.equal(patched.variant,'dynamic-b');
assert.equal(context.overlay(original),patched);
assert.ok('settings' in patched);
assert.ok(Object.keys(patched).includes('settings'));
assert.equal(JSON.parse(JSON.stringify(patched)).newChat,'新建对话');
assert.equal(original.newChat,'New chat');
console.log('PASS: final provider overlay, frozen upstream proxy, dynamic variants, unknown/secret messages, cached identity, enumeration');
